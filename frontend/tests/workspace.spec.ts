import { expect, test } from '@playwright/test';

const backend = process.env.PLAYWRIGHT_API_URL ?? 'http://127.0.0.1:8001';

test('public demo is useful and read-only', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: /Good (morning|afternoon|evening)/ })).toBeVisible();
  await expect(page.getByText('A real workflow. Fictional candidates.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Create a job', exact: true })).toHaveCount(0);
  await page.getByRole('navigation').getByRole('button', { name: 'Candidates' }).click();
  await expect(page.getByRole('table')).toBeVisible();
  const rows = page.locator('tbody tr');
  expect(await rows.count()).toBeGreaterThan(0);
  const firstName = await page.locator('.candidate-cell strong').first().innerText();
  await page.getByRole('textbox', { name: 'Filter candidates' }).fill(firstName);
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: `View ${firstName}`, exact: true }).click();
  await page.getByRole('tab', { name: 'Screening', exact: true }).click();
  await expect(page.getByText('What supports this match?')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Update stage' })).toHaveCount(0);
  await expect(page.locator('.evidence-item').first()).toBeVisible();
});

test('staff can create, screen, review, and assess a synthetic candidate', async ({ page, request, context }) => {
  test.setTimeout(120_000);
  const config = await request.get(`${backend}/api/config`).then(r => r.json());
  test.skip(!config.local_login, 'This test requires explicitly enabled local development authentication.');
  const suffix = Date.now(); const title = `E2E Python Engineer ${suffix}`; const candidateName = `Demo Reviewer ${suffix}`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Staff sign in' }).click();
  await page.getByLabel('Email address', { exact: true }).fill('admin@demo.local');
  await page.getByLabel('Password', { exact: true }).fill(process.env.LOCAL_DEMO_PASSWORD ?? 'local-demo-only');
  await page.getByRole('button', { name: 'Sign in to workspace' }).click();
  await expect(page.getByRole('button', { name: 'Create a job', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Create a job', exact: true }).click();
  await page.getByLabel('Job title', { exact: true }).fill(title);
  await page.getByLabel('Job description', { exact: true }).fill('Build Python backend services. Demonstrate Python experience through specific projects and tests.');
  await page.getByRole('button', { name: 'Add criterion', exact: true }).click();
  await page.getByLabel('Criterion 1', { exact: true }).fill('Python');
  await page.getByRole('checkbox', { name: /I’ve reviewed and approve/ }).check();
  await page.getByRole('button', { name: 'Create job opening', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('job opening is ready');
  const token = await page.evaluate(() => sessionStorage.getItem('hireline_token'));
  const headers = { Authorization: `Bearer ${token}` };
  const snapshot = await request.get(`${backend}/api/workspace`, { headers }).then(r => r.json());
  const job = snapshot.jobs.find((j: { title: string }) => j.title === title);
  expect(job).toBeTruthy();
  const createCandidate = await request.post(`${backend}/api/candidates`, { headers, data: { name: candidateName, email: 'fictional@example.test', headline: 'Synthetic Python engineer', skills: ['Python'], resume_text: `${candidateName}\nBuilt Python APIs with FastAPI and automated tests.\nWorked on Python production services for four years.`, synthetic_confirmed: true } });
  expect(createCandidate.ok()).toBeTruthy();
  const candidate = await createCandidate.json();
  const createApplication = await request.post(`${backend}/api/jobs/${job.id}/applications`, { headers, data: { candidate_id: candidate.id } });
  expect(createApplication.ok()).toBeTruthy();
  await page.reload();
  await page.getByRole('navigation').getByRole('button', { name: 'Candidates' }).click();
  await page.getByRole('textbox', { name: 'Filter candidates' }).fill(candidateName);
  await page.getByRole('button', { name: `View ${candidateName}`, exact: true }).click();
  await page.getByRole('tab', { name: 'Screening', exact: true }).click();
  await page.getByRole('button', { name: 'Start screening', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Review screening', exact: true })).toBeVisible({ timeout: 40_000 });
  await expect(page.locator('.evidence-item blockquote').first()).toBeVisible();
  await page.getByRole('button', { name: 'Review screening', exact: true }).click();
  await page.getByLabel('Review notes', { exact: true }).fill('Checked source evidence against the Python requirement.');
  await page.getByRole('button', { name: 'Approve screening review', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Take a closer look' })).toHaveCount(0);
  await page.getByRole('tab', { name: 'Assessment', exact: true }).click();
  await page.getByRole('button', { name: 'Create assessment', exact: true }).click();
  await page.getByRole('checkbox', { name: /I approve these questions/ }).check();
  await page.getByRole('button', { name: 'Approve & create invitation', exact: true }).click();
  const invite = await page.getByLabel('Candidate invitation link', { exact: true }).inputValue();
  const candidatePage = await context.newPage();
  await candidatePage.goto(invite);
  await candidatePage.getByRole('radio', { name: 'Parameterized queries', exact: true }).check();
  await candidatePage.getByRole('radio', { name: 'To make related operations atomic', exact: true }).check();
  await candidatePage.getByRole('textbox', { name: /Describe a technical problem/ }).fill('In this fictional project, I built a Python API, chose parameterized SQL for safety, and verified failures with automated tests.');
  await candidatePage.getByRole('button', { name: 'Add availability', exact: true }).click();
  const future = await candidatePage.evaluate(() => {
    const start = new Date(); start.setDate(start.getDate() + 2); start.setHours(10, 0, 0, 0);
    const local = (date: Date) => new Date(date.getTime() - date.getTimezoneOffset() * 60000).toISOString().slice(0, 16);
    return { start: local(start), end: local(new Date(start.getTime() + 3600000)) };
  });
  await candidatePage.getByLabel('Available from', { exact: true }).fill(future.start);
  await candidatePage.getByLabel('Until', { exact: true }).fill(future.end);
  await candidatePage.getByRole('checkbox', { name: /I am submitting fictional demo responses/ }).check();
  await candidatePage.getByRole('button', { name: 'Submit my responses', exact: true }).click();
  await expect(candidatePage.getByRole('heading', { name: /Thanks for sharing/ })).toBeVisible();
  await candidatePage.reload();
  await expect(candidatePage.getByRole('heading', { name: /Thanks for sharing/ })).toBeVisible();
  await candidatePage.close();
  await page.bringToFront();
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.getByRole('tab', { name: 'Assessment', exact: true }).click();
  await page.getByRole('button', { name: 'Review responses', exact: true }).click();
  await page.getByLabel('Reviewer notes', { exact: true }).fill('Reviewed the fictional answers against the approved rubric.');
  await page.getByRole('checkbox', { name: /I have reviewed the candidate responses/ }).check();
  await page.getByRole('button', { name: 'Record assessment review', exact: true }).click();
  await page.getByRole('tab', { name: 'Interviews', exact: true }).click();
  await page.getByRole('button', { name: 'Schedule interview', exact: true }).click();
  await expect(page.getByLabel('Interview start', { exact: true })).toHaveValue(future.start);
  await page.getByRole('checkbox', { name: /I approve this interview/ }).check();
  await page.getByRole('button', { name: 'Confirm interview booking', exact: true }).click();
  await expect(page.locator('.interview-detail')).toContainText('Preview', { timeout: 25_000 });
  await page.getByRole('button', { name: 'Record interview feedback', exact: true }).click();
  await page.getByLabel('Your observations', { exact: true }).fill('The fictional candidate explained concrete tradeoffs and verified the implementation with tests.');
  await page.getByRole('button', { name: 'Save team feedback', exact: true }).click();
  await page.getByRole('button', { name: 'Update stage', exact: true }).click();
  await page.getByRole('combobox', { name: 'Application stage', exact: true }).selectOption('hired');
  await page.getByLabel(/Decision note/).fill('Recruiter recorded the fictional outcome after reviewing all evidence.');
  await page.getByRole('button', { name: 'Confirm stage change', exact: true }).click();
  await expect(page.locator('.candidate-detail-header')).toContainText('Hired');
});

test('mobile navigation remains accessible', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.getByRole('table')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'Job openings' }).click();
  await expect(page.getByRole('heading', { name: 'Job openings.' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Open navigation' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
});
